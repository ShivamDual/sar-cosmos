/* SAR Cosmos front-end. No framework, no build step -- vanilla JS against
   window.SAR_COSMOS_DATA (see data.js, generated by
   scripts/export_static_data.py). */

(function () {
  "use strict";

  var DATA = window.SAR_COSMOS_DATA;
  var REDUCED_MOTION = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  var lakesById = {};
  DATA.lakes.forEach(function (lake) { lakesById[lake.id] = lake; });
  var selectedId = DATA.lakes[0].id;

  // ---------------------------------------------------------------- stats

  function renderStats() {
    document.getElementById("stat-dangerous").textContent = DATA.stats.dangerousLakes;
    document.getElementById("stat-monitored").textContent = DATA.stats.monitoredLakes;
    document.getElementById("stat-glof").textContent = DATA.stats.glofEventsSince1977;
    document.getElementById("stat-risk").textContent = DATA.stats.worstCaseHydropowerRisk;
  }

  // ------------------------------------------------------------- pill row

  function renderPills() {
    var row = document.getElementById("pill-row");
    row.innerHTML = "";
    DATA.lakes.forEach(function (lake) {
      var btn = document.createElement("button");
      btn.className = "pill" + (lake.id === selectedId ? " active" : "");
      btn.textContent = lake.name;
      btn.setAttribute("data-lake-id", lake.id);
      btn.addEventListener("click", function () { selectLake(lake.id); });
      row.appendChild(btn);
    });
  }

  function syncPills() {
    document.querySelectorAll(".pill").forEach(function (btn) {
      btn.classList.toggle("active", btn.getAttribute("data-lake-id") === selectedId);
    });
  }

  // ---------------------------------------------------------- detail panel

  var RISK_LABEL_CLASS = { Critical: "critical" };

  function fmtPct(v) {
    if (v === null || v === undefined) return "n/a";
    var sign = v > 0 ? "+" : "";
    return sign + v.toFixed(1) + "%";
  }

  function renderDetail(lake) {
    var panel = document.getElementById("detail-panel");
    var badgeClass = RISK_LABEL_CLASS[lake.riskTier] || "";
    panel.classList.remove("detail");
    void panel.offsetWidth; // restart the crossfade animation
    panel.classList.add("detail");
    panel.innerHTML =
      '<div class="panel-title">' + lake.name + "</div>" +
      '<span class="risk-badge ' + badgeClass + '" style="color:' + lake.riskColor +
        '; border-color:' + lake.riskColor + "33; background:" + lake.riskColor + '14;">' +
        '<span class="risk-dot" style="background:' + lake.riskColor + ';"></span>' +
        lake.riskTier + " risk</span>" +
      '<p class="context-line">' + lake.context + " Sits at roughly " +
        lake.altitude_m.toLocaleString() + " m in the " + lake.basin + " basin, " +
        lake.district + " district.</p>" +
      '<div class="data-note">3-yr change: ' + fmtPct(lake.change3yrPct) +
        "   ·   5-yr change: " + fmtPct(lake.change5yrPct) + "</div>" +
      '<div class="data-note">Key figure: ' + lake.keyStat + "</div>";
  }

  // --------------------------------------------------------------- chart

  var chart;

  function initChart() {
    var ctx = document.getElementById("trend-chart").getContext("2d");
    chart = new Chart(ctx, {
      type: "line",
      data: { datasets: [] },
      options: {
        responsive: true,
        maintainAspectRatio: false,
        animation: { duration: 500 },
        interaction: { mode: "nearest", intersect: false },
        scales: {
          x: {
            type: "time",
            time: { unit: "year" },
            grid: { color: "rgba(244,241,234,0.06)" },
            ticks: { color: "#8FA3C4", font: { family: "Manrope" } },
          },
          y: {
            title: { display: true, text: "Area (km²)", color: "#8FA3C4" },
            grid: { color: "rgba(244,241,234,0.06)" },
            ticks: { color: "#8FA3C4", font: { family: "JetBrains Mono" } },
          },
        },
        plugins: {
          legend: {
            position: "top",
            align: "start",
            labels: { color: "#F4F1EA", font: { family: "Manrope" }, boxWidth: 12, usePointStyle: true },
          },
          tooltip: {
            backgroundColor: "#16304F",
            titleColor: "#F4F1EA",
            bodyColor: "#F4F1EA",
            borderColor: "rgba(244,241,234,0.09)",
            borderWidth: 1,
          },
        },
      },
    });
  }

  function updateChart(lake) {
    chart.data.datasets = [
      {
        label: "Optical (Sentinel-2 / Landsat)",
        data: lake.optical.map(function (p) { return { x: p.date, y: p.area }; }),
        borderColor: "#3FD8C5",
        backgroundColor: "rgba(63,216,197,0.12)",
        pointRadius: 2,
        borderWidth: 2,
        fill: true,
        tension: 0.25,
      },
      {
        label: "NISAR (SAR, cloud-penetrating)",
        data: lake.sar.map(function (p) { return { x: p.date, y: p.area }; }),
        borderColor: "#FBBF24",
        backgroundColor: "#FBBF24",
        showLine: false,
        pointStyle: "rectRot",
        pointRadius: 5,
      },
    ];
    chart.update();
  }

  // ---------------------------------------------------------------- map

  var map, markersById = {};

  function initMap() {
    var avgLat = DATA.lakes.reduce(function (s, l) { return s + l.lat; }, 0) / DATA.lakes.length;
    var avgLon = DATA.lakes.reduce(function (s, l) { return s + l.lon; }, 0) / DATA.lakes.length;

    map = L.map("map", { scrollWheelZoom: false }).setView([avgLat, avgLon], 8);
    L.tileLayer("https://server.arcgisonline.com/ArcGIS/rest/services/World_Imagery/MapServer/tile/{z}/{y}/{x}", {
      attribution: "Tiles &copy; Esri &mdash; Source: Esri, i-cubed, USDA, USGS, AEX, GeoEye, Getmapping, Aerogrid, IGN, IGP, UPR-EGP, and the GIS User Community",
      maxZoom: 18,
    }).addTo(map);

    DATA.lakes.forEach(function (lake) {
      var marker = L.circleMarker([lake.lat, lake.lon], {
        radius: 8,
        color: lake.riskColor,
        fillColor: lake.riskColor,
        fillOpacity: 0.65,
        weight: 2,
      }).addTo(map);
      marker.bindPopup("<b>" + lake.name + "</b><br>" + lake.riskTier + " risk");
      marker.on("click", function () { selectLake(lake.id); });
      markersById[lake.id] = marker;
    });
  }

  function syncMap(lake) {
    Object.keys(markersById).forEach(function (id) {
      markersById[id].setStyle({ radius: id === lake.id ? 12 : 8, weight: id === lake.id ? 3 : 2 });
    });
    map.panTo([lake.lat, lake.lon]);
    markersById[lake.id].openPopup();
  }

  // ----------------------------------------------------- selection root

  function selectLake(id) {
    if (!lakesById[id]) return;
    selectedId = id;
    var lake = lakesById[id];
    syncPills();
    renderDetail(lake);
    updateChart(lake);
    syncMap(lake);
    highlight3DMarker(id);
  }

  // ------------------------------------------------------- 3D hero scene

  var highlight3DMarker = function () {}; // replaced once the scene is built, no-op until then

  function initScene() {
    var heroEl = document.querySelector(".hero");
    var canvas = document.getElementById("scene");
    var renderer = new THREE.WebGLRenderer({ canvas: canvas, antialias: true, alpha: true });
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));

    var scene = new THREE.Scene();
    var camera = new THREE.PerspectiveCamera(50, 1, 0.1, 100);
    camera.position.set(0, 0.6, 6.4);
    camera.lookAt(0, 0, 0);

    function sizeToHero() {
      var w = heroEl.clientWidth, h = heroEl.clientHeight;
      renderer.setSize(w, h, false);
      camera.aspect = w / h;
      camera.updateProjectionMatrix();
    }
    sizeToHero();
    window.addEventListener("resize", sizeToHero);

    // Starfield
    var starGeo = new THREE.BufferGeometry();
    var starCount = 900;
    var starPositions = new Float32Array(starCount * 3);
    for (var i = 0; i < starCount; i++) {
      var radius = 20 + Math.random() * 40;
      var theta = Math.random() * Math.PI * 2;
      var phi = Math.acos(2 * Math.random() - 1);
      starPositions[i * 3] = radius * Math.sin(phi) * Math.cos(theta);
      starPositions[i * 3 + 1] = radius * Math.sin(phi) * Math.sin(theta);
      starPositions[i * 3 + 2] = radius * Math.cos(phi);
    }
    starGeo.setAttribute("position", new THREE.Float32BufferAttribute(starPositions, 3));
    var starMat = new THREE.PointsMaterial({ color: 0xf4f1ea, size: 0.045, transparent: true, opacity: 0.55 });
    scene.add(new THREE.Points(starGeo, starMat));

    // Globe: dim solid core + wireframe shell
    var globeGroup = new THREE.Group();
    var coreGeo = new THREE.SphereGeometry(2.15, 32, 24);
    var coreMat = new THREE.MeshBasicMaterial({ color: 0x0a1a30, transparent: true, opacity: 0.9 });
    globeGroup.add(new THREE.Mesh(coreGeo, coreMat));

    var wireGeo = new THREE.SphereGeometry(2.2, 22, 16);
    var wireMat = new THREE.MeshBasicMaterial({ color: 0x3fd8c5, wireframe: true, transparent: true, opacity: 0.22 });
    globeGroup.add(new THREE.Mesh(wireGeo, wireMat));
    scene.add(globeGroup);

    // Lake markers on the globe surface, from real lat/lon
    var GLOBE_R = 2.2;
    function latLonToVec3(lat, lon, r) {
      var phi = (90 - lat) * (Math.PI / 180);
      var theta = (lon + 180) * (Math.PI / 180);
      return new THREE.Vector3(
        -r * Math.sin(phi) * Math.cos(theta),
        r * Math.cos(phi),
        r * Math.sin(phi) * Math.sin(theta)
      );
    }

    var markerMeshes = [];
    DATA.lakes.forEach(function (lake) {
      var pos = latLonToVec3(lake.lat, lake.lon, GLOBE_R * 1.01);
      var geo = new THREE.SphereGeometry(0.045, 10, 10);
      var color = new THREE.Color(lake.riskColor);
      var mat = new THREE.MeshBasicMaterial({ color: color });
      var mesh = new THREE.Mesh(geo, mat);
      mesh.position.copy(pos);
      mesh.userData.lakeId = lake.id;
      mesh.userData.baseScale = 1;
      globeGroup.add(mesh);
      markerMeshes.push(mesh);
    });

    highlight3DMarker = function (id) {
      markerMeshes.forEach(function (m) {
        var isSel = m.userData.lakeId === id;
        var s = isSel ? 1.9 : 1;
        m.scale.set(s, s, s);
      });
    };
    highlight3DMarker(selectedId);

    // Satellite: body + two panels, orbiting the globe
    var satGroup = new THREE.Group();
    var bodyGeo = new THREE.BoxGeometry(0.12, 0.12, 0.2);
    var bodyMat = new THREE.MeshBasicMaterial({ color: 0xf4f1ea });
    satGroup.add(new THREE.Mesh(bodyGeo, bodyMat));

    var panelGeo = new THREE.BoxGeometry(0.34, 0.01, 0.12);
    var panelMat = new THREE.MeshBasicMaterial({ color: 0x3fd8c5 });
    var panelL = new THREE.Mesh(panelGeo, panelMat); panelL.position.x = -0.28;
    var panelR = new THREE.Mesh(panelGeo, panelMat); panelR.position.x = 0.28;
    satGroup.add(panelL, panelR);

    var dishGeo = new THREE.CylinderGeometry(0.04, 0.06, 0.04, 12);
    var dishMat = new THREE.MeshBasicMaterial({ color: 0x8fa3c4 });
    var dish = new THREE.Mesh(dishGeo, dishMat);
    dish.rotation.x = Math.PI / 2;
    dish.position.z = 0.14;
    satGroup.add(dish);

    scene.add(satGroup);

    // Raycaster: click a marker in the 3D scene to select that lake
    var raycaster = new THREE.Raycaster();
    var pointer = new THREE.Vector2();
    canvas.addEventListener("click", function (evt) {
      var rect = canvas.getBoundingClientRect();
      pointer.x = ((evt.clientX - rect.left) / rect.width) * 2 - 1;
      pointer.y = -((evt.clientY - rect.top) / rect.height) * 2 + 1;
      raycaster.setFromCamera(pointer, camera);
      var hits = raycaster.intersectObjects(markerMeshes);
      if (hits.length > 0) selectLake(hits[0].object.userData.lakeId);
    });

    var clock = new THREE.Clock();
    var orbitRadius = 3.4;

    function animate() {
      requestAnimationFrame(animate);
      var t = clock.getElapsedTime();
      if (!REDUCED_MOTION) {
        globeGroup.rotation.y = t * 0.06;
        var angle = t * 0.35;
        satGroup.position.set(
          orbitRadius * Math.cos(angle),
          Math.sin(angle * 0.7) * 0.9,
          orbitRadius * Math.sin(angle)
        );
        satGroup.lookAt(0, 0, 0);
      }
      renderer.render(scene, camera);
    }
    animate();
  }

  // ------------------------------------------------------------ bootstrap

  document.addEventListener("DOMContentLoaded", function () {
    renderStats();
    renderPills();
    initMap();
    initChart();
    selectLake(selectedId);
    if (window.THREE) initScene();
  });
})();
